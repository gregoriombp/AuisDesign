#!/usr/bin/env node
/**
 * Builds kit/ui/src/styles/chrome.css from chrome.source.css.
 *
 *   npm run ui:css
 *
 * Tailwind compiles the source (only kit/ui/src is scanned), then the output is
 * made safe to drop into someone else's app:
 *
 *  - every rule is scoped under [data-auis-ui] (`:root`/`html`/`body` become
 *    the chrome's root itself), so nothing leaks onto the host's elements;
 *  - cascade layers are flattened in their order (theme, base, components,
 *    utilities, then the unlayered primitives): a layered rule loses to ANY
 *    unlayered rule of the host, whatever its specificity;
 *  - Tailwind's --tw-* variables (and their @property registrations) become
 *    --auis-tw-*, so the chrome never changes how a host's own --tw-* behave;
 *  - @keyframes get an `auis-` prefix, so a host's `spin` or `enter` is not
 *    replaced by ours (or ours by theirs);
 *  - rem becomes px: a host that sets `html { font-size: 62.5% }` does not
 *    shrink the chrome.
 *
 * kit/ui/src/__tests__/chrome-css.test.ts fails when chrome.css is stale or
 * when any of the above does not hold.
 */
import { readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import postcss from "postcss"
import tailwind from "@tailwindcss/postcss"

const STYLES = path.resolve(import.meta.dirname, "../src/styles")
export const SOURCE = path.join(STYLES, "chrome.source.css")
export const OUTPUT = path.join(STYLES, "chrome.css")

export const SCOPE = "[data-auis-ui]"
const LAYER_ORDER = ["properties", "theme", "base", "components", "utilities"]

const HEADER = `/* GENERATED by kit/ui/scripts/build-css.mjs from chrome.source.css — do not
 * edit by hand: change the source and run \`npm run ui:css\`. */
`

function scopeSelector(selector) {
  const s = selector.trim()
  if (s.includes(SCOPE)) return s
  if (/^(:root|:host|html|body)$/.test(s)) return SCOPE
  // `.dark` sits on <html>, above the chrome's root.
  if (s.startsWith(".dark ")) return `.dark ${SCOPE} ${s.slice(6)}`
  return `${SCOPE} ${s}`
}

const insideKeyframes = (node) => {
  for (let p = node.parent; p; p = p.parent) {
    if (p.type === "atrule" && /keyframes$/.test(p.name)) return true
  }
  return false
}

const pxFromRem = (value) =>
  value.replace(/(-?\d*\.?\d+)rem\b/g, (_, n) => `${Number((Number(n) * 16).toFixed(4))}px`)

/** Scope, flatten and rename a compiled stylesheet (exported for the test). */
export function finish(css) {
  const root = postcss.parse(css)
  const buckets = new Map(LAYER_ORDER.map((name) => [name, []]))
  const unlayered = []
  let license = null
  root.each((node) => {
    if (node.type === "comment") {
      if (!license && node.text.startsWith("!")) license = node.clone()
      return
    }
    if (node.type === "atrule" && node.name === "layer") {
      if (!node.nodes) return // `@layer a, b;` — the order is now the file's order
      const bucket = buckets.get(node.params.trim()) ?? unlayered
      node.each((child) => {
        bucket.push(child.clone())
      })
      return
    }
    unlayered.push(node.clone())
  })

  const out = postcss.root()
  if (license) out.append(license)
  for (const name of LAYER_ORDER) out.append(...buckets.get(name))
  out.append(...unlayered)

  out.walkRules((rule) => {
    if (insideKeyframes(rule)) return
    rule.selectors = [...new Set(rule.selectors.map(scopeSelector))]
  })

  const keyframes = new Set()
  out.walkAtRules((at) => {
    if (/keyframes$/.test(at.name) && !at.params.startsWith("auis-")) {
      keyframes.add(at.params)
      at.params = `auis-${at.params}`
    }
    if (at.name === "property") at.params = at.params.replace(/^--tw-/, "--auis-tw-")
    if (at.name === "media" || at.name === "supports") at.params = pxFromRem(at.params)
  })
  const names = [...keyframes].sort((a, b) => b.length - a.length)
  out.walkDecls((decl) => {
    decl.prop = decl.prop.replace(/^--tw-/, "--auis-tw-")
    let value = decl.value.replace(/--tw-/g, "--auis-tw-")
    if (/^(animation|animation-name)$/.test(decl.prop) || decl.prop.startsWith("--")) {
      for (const name of names) {
        value = value.replace(new RegExp(`(?<![\\w-])${name}(?![\\w-])`, "g"), `auis-${name}`)
      }
    }
    decl.value = pxFromRem(value)
  })

  return HEADER + out.toString().trimEnd() + "\n"
}

export async function buildChromeCss() {
  const source = await readFile(SOURCE, "utf8")
  const result = await postcss([tailwind({ optimize: { minify: false } })]).process(source, {
    from: SOURCE,
  })
  return finish(result.css)
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const css = await buildChromeCss()
  await writeFile(OUTPUT, css)
  console.log(`${path.relative(process.cwd(), OUTPUT)}: ${css.length} bytes`)
}
